#!/usr/bin/env python
"""Generate clearly-labelled SYNTHETIC cohorts for pipeline smoke-testing.

This does NOT recreate the real GEO data. It fabricates small matrices with the
same structure (samples x genes, coldata, per-cell-line groups, a batch shift
between datasets, and a planted resistance signal) so that Phases 4-8 can be
exercised end-to-end without the real downloads.

Outputs (under data/_synthetic/):
    GSE202859/expression_processed.csv + coldata.csv   (discovery cell lines)
    GSE193258/expression_processed.csv + coldata.csv   (validation cell lines)
    README_SYNTHETIC.txt

Run:
    python scripts/make_synthetic_data.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ml.config import load_project, set_global_seed  # noqa: E402

N_GENES = 1500
N_SIGNAL = 40          # genes planted as resistance-associated
BATCH_SHIFT = 0.8      # dataset-level distribution shift between cohorts
LINES = ["PC9", "H1975", "HCC827"]


def _genes():
    return pd.Index([f"GENE{i:04d}" for i in range(N_GENES)])


def _build_cohort(rng, accession, batch_shift, shared_frac, seed_tag):
    samples, donors, conds = [], [], []
    for line in LINES:
        for rep in range(1, 4):
            samples.append(f"{accession}_{line}_S{rep}")
            donors.append(line)
            conds.append("Sensitive")
        for rep in range(1, 4):
            samples.append(f"{accession}_{line}_R{rep}")
            donors.append(line)
            conds.append("Resistant")
    n = len(samples)
    base = rng.normal(6.0, 1.2, size=(n, N_GENES)) + batch_shift
    y = np.array([1 if c == "Resistant" else 0 for c in conds])

    n_shared = int(N_SIGNAL * shared_frac)
    base[:, :n_shared] += np.outer(y, rng.normal(1.3, 0.2, size=n_shared))
    base[:, n_shared:N_SIGNAL] += np.outer(y, rng.normal(0.5, 0.2, size=N_SIGNAL - n_shared))
    # cohort-private signal (should NOT survive cross-dataset validation)
    base[:, N_SIGNAL:N_SIGNAL + 40] += np.outer(y, rng.normal(0.8, 0.2, size=40))

    X = pd.DataFrame(base, index=pd.Index(samples), columns=_genes())
    coldata = pd.DataFrame({"sample": samples, "condition": conds,
                            "cohort": accession, "donor": donors,
                            "cell_line": donors})
    return X, coldata


def write_cohort(project, accession, X, coldata):
    dest = project.synthetic / accession
    dest.mkdir(parents=True, exist_ok=True)
    out = X.copy()
    out.insert(0, "sample", out.index)
    out.to_csv(dest / "expression_processed.csv", index=False)
    coldata.to_csv(dest / "coldata.csv", index=False)
    print(f"  wrote {dest/'expression_processed.csv'}  ({X.shape[0]} x {X.shape[1]})")
    print(f"  wrote {dest/'coldata.csv'}")


def main():
    project = load_project()
    set_global_seed(project.cfg["project"]["seed"])
    rng = np.random.default_rng(project.cfg["project"]["seed"])
    project.synthetic.mkdir(parents=True, exist_ok=True)

    print("Generating SYNTHETIC discovery cohort (GSE202859)...")
    Xd, cdd = _build_cohort(rng, "GSE202859", batch_shift=0.0, shared_frac=1.0, seed_tag="d")
    write_cohort(project, "GSE202859", Xd, cdd)

    print("Generating SYNTHETIC validation cohort (GSE193258)...")
    Xv, cdv = _build_cohort(rng, "GSE193258", batch_shift=BATCH_SHIFT,
                            shared_frac=0.6, seed_tag="v")
    write_cohort(project, "GSE193258", Xv, cdv)

    readme = (
        "SYNTHETIC DATA - NOT REAL GEO DATA.\n"
        "Generated by scripts/make_synthetic_data.py for pipeline smoke-testing.\n"
        "Structure mimics the real cohorts (samples x genes, coldata, per-cell-line\n"
        "groups, a batch shift between datasets, and a planted resistance signal).\n"
        "Do not use for scientific conclusions.\n"
    )
    (project.synthetic / "README_SYNTHETIC.txt").write_text(readme, encoding="utf-8")
    print(f"Done. Synthetic data in {project.synthetic}")


if __name__ == "__main__":
    main()
